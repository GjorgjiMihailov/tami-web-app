<?php

namespace App\Support\Payroll\Mpin;

use App\Models\PayrollRun;
use App\Models\PayrollRunLine;
use App\Support\Payroll\MpinObvrznik;
use SimpleXMLElement;

/**
 * Проверките што УЈП сама ги врти по поднесување, направени пред симнување.
 *
 * Изворот е `poraki.html` од помошта на МПИН клиентот, каде секоја порака носи
 * тежина: 2 = грешка, 1 = предупредување. Истата поделба се задржува овде, за
 * да не се блокира извоз поради нешто што УЈП само би го предупредила.
 */
final class MpinValidator
{
    public static function check(PayrollRun $run): MpinValidationResult
    {
        $run->loadMissing(['company', 'employees.employee', 'employees.lines']);

        $errors = [];
        $warnings = [];

        if ($run->isDraft()) {
            $errors[] = 'Пресметката мора да биде потврдена пред извоз.';
        }

        if (! $run->company->tax_id) {
            $errors[] = 'Фирмата нема внесен ЕДБ.';
        }

        if (! $run->company->mpin_obvrznik_code) {
            $errors[] = 'Фирмата нема внесен вид обврзник за МПИН.';
        }

        if ($run->employees->isEmpty()) {
            $errors[] = 'Пресметката нема ниту еден работник.';
        }

        // Видот обврзник по кој оваа пресметка НАВИСТИНА е пресметана, истиот
        // што градителот го пишува во заглавието. Резервата 110 ги опишува
        // редовите отворени пред колоната да постои — види
        // MpinDocumentBuilder::build().
        $obvrznik = $run->mpin_obvrznik_code ?? MpinObvrznik::EMPLOYER;

        // Картонот на фирмата е сменет откако оваа пресметка е пресметана.
        // Датотеката е исправна — потврдена пресметка одбива да се пресмета
        // повторно, па видот по кој е пресметана е единствениот што може да го
        // напише без сама да си противречи. Тивко е она што е проблем:
        // сметководителот што свесно го сменил картонот симнува датотека со
        // стариот вид и ништо не му кажува зошто. Предупредување, не грешка.
        $onCard = $run->company->mpin_obvrznik_code;

        if ($onCard !== null && $onCard !== $obvrznik) {
            $warnings[] = "Оваа пресметка е пресметана како обврзник {$obvrznik->value}, а фирмата сега е означена како {$onCard->value}. Датотеката се извезува како {$obvrznik->value}; новиот вид важи од следната пресметка.";
        }

        foreach ($run->employees as $row) {
            $employee = $row->employee;
            $name = trim($employee->first_name.' '.$employee->last_name);

            // Секое поле го носи целото договорено „нема внесен(а) ...“ до
            // грешката, наместо еден заеднички шаблон со гол именик: ЕМБГ е
            // машки род („нема внесен ЕМБГ“, види EmployeeForm.php:232), а
            // сметка/шифра/служба се женски род („нема внесена ...“). Едно
            // споделено сложување не може да ги согласи двете.
            foreach ([
                'embg' => 'нема внесен ЕМБГ',
                'bank_account' => 'нема внесена трансакциска сметка',
                'municipality_code' => 'нема внесена шифра на општина',
                'health_area_code' => 'нема внесена подрачна здравствена служба',
                'insurance_type_code' => 'нема внесена шифра за вид на стаж',
                // Task 7-то откритие: SifraDvizenje доаѓа од movement_code,
                // кое е nullable, дефолт null во фабриката и во формата кога е
                // празно. Празно поле поминува низ градителот како валиден
                // XML — <SifraDvizenje></SifraDvizenje> — и УЈП го одбива при
                // поднесување.
                'movement_code' => 'нема внесена шифра на движење',
            ] as $column => $message) {
                if (! $employee->{$column}) {
                    $errors[] = "{$name}: {$message}.";
                }
            }

            // Шифрата за ослободување е задолжителна САМО за обврзник 111.
            // Придонесот за вработување кај 111 се пишува нула по основ на
            // шифрата 001 („Самостоен вршител ослободен од плаќање на придонес
            // за вработување") — без неа датотеката носи нулти придонес без
            // ништо што го оправдува, добро оформена и одбиена. Безусловно
            // правило не доаѓа предвид: вистинската прифатена датотека за
            // обврзник 110 носи празен `SifraOsloboduvanje`.
            if ($obvrznik === MpinObvrznik::SELF_EMPLOYED && ! $employee->exemption_code) {
                $errors[] = "{$name}: нема внесена шифра за ослободување, а обврзник 111 го пишува придонесот за вработување нула токму по неа.";
            }

            // Заштитна мрежа за расчекор меѓу зачуваниот вид обврзник и
            // зачуваните цифри. Пресметката веќе го чува видот обврзник по кој
            // е пресметана, па нормално двете не можат да се разидат — ова
            // фаќа рачна интервенција во базата или пат што тоа зачувување не
            // го покрива. Поправката е бришење и повторно отворање: потврдена
            // пресметка одбива да се пресмета повторно, па цифрите не можат да
            // се порамнат на самото место.
            if (! $obvrznik->chargesUnemployment() && (round($row->unemployment) > 0 || round($row->tax) > 0)) {
                $errors[] = "{$name}: пресметката е означена како обврзник 111, а носи придонес за вработување или личен данок, што 111 не плаќа — избришете ја пресметката и отворете ја повторно.";
            }

            if ($obvrznik->chargesUnemployment() && round($row->unemployment) <= 0 && round($row->gross) > 0) {
                $errors[] = "{$name}: пресметката е означена како обврзник 110, а придонесот за вработување е нула — избришете ја пресметката и отворете ја повторно.";
            }

            // Нулата е намерна ознака за аномалија од фазата за делумни месеци:
            // работник чии датуми се сменети откако пресметката е отворена. УЈП
            // фиксира вредност меѓу 1 и бројот денови во месецот, па нулата е
            // нелегална и мора да запре тука.
            if ($row->staz_days < 1) {
                $errors[] = "{$name}: нула денови стаж — датумите на вработување не го покриваат месецот.";
            }

            if (round($row->gross) <= 0) {
                $errors[] = "{$name}: бруто износот е нула, што УЈП не го прифаќа без потврда.";
            }

            $hourLines = $row->lines->where('kind', PayrollRunLine::KIND_HOURS);

            if ($hourLines->isEmpty()) {
                $errors[] = "{$name}: нема ниту една линија со часови.";
            }

            foreach ($hourLines as $line) {
                if ((int) $line->hours > 0 && round($line->amount) <= 0) {
                    $errors[] = "{$name}: линијата „{$line->description}“ има часови без износ.";
                }

                if ((int) $line->hours <= 0 && round($line->amount) > 0) {
                    $errors[] = "{$name}: линијата „{$line->description}“ има износ без часови.";
                }
            }

            // ПРИВРЕМЕНА БРАНА — се тргне штом пристигне вистинска датотека.
            //
            // Линија што не е ниту часови ниту задршка е износ: минат труд,
            // храна, превоз, награда. Градителот ја пишува како засебен ред на
            // ниво 3 со нула часови и нула денови стаж. Нула денови стаж е
            // вредност што овој ист валидатор ја одбива едно ниво погоре, па
            // тврдиме едно правило на едно место и го кршиме на друго.
            //
            // Обликот е изведен од шифрарникот rab_cas, кој 037 „Минат труд" и
            // 034 „Награда - износ" ги наведува рамо до рамо со 001 „Редовни
            // работни часови" — но ниту една од двете вистински прифатени
            // датотеки не го покрива тој пат. Обете ставаат цело бруто во еден
            // ред, и обете се за работник без стаж, па не кажуваат ни дали
            // минатиот труд воопшто е засебен ред.
            //
            // Затоа извозот застанува тука. Една вистинска поднесена датотека
            // со минат труд или надоместок го затвора прашањето; дотогаш
            // погодувањето би завршило во документ што оди во УЈП.
            $amountLines = $row->lines
                ->reject(fn (PayrollRunLine $line) => in_array(
                    $line->kind,
                    [PayrollRunLine::KIND_HOURS, PayrollRunLine::KIND_DEDUCTION],
                    true,
                ));

            foreach ($amountLines as $line) {
                $errors[] = "{$name}: линијата „{$line->description}“ е износ без часови, а обликот на таквиот ред во МПИН сè уште не е потврден со вистинска поднесена датотека — извозот е запрен намерно.";
            }

            $fund = $employee->monthFund($run->month_hours);
            $worked = (int) $hourLines->sum('hours');

            // Предупредување, не грешка: работник кодиран 0047 (неполно
            // работно време) чии внесени часови оваа пресметка сепак излегуваат
            // на ниво на цел фонд. Ова е засебно од директната проверка подолу:
            // таа гледа во договорот (weekly_hours), а оваа во она што реално е
            // внесено во пресметката — фаќа рачно поместени часови кај
            // вработен чиј договор и шифра инаку се согласуваат.
            if ($employee->insurance_type_code === '0047' && $worked >= $run->month_hours) {
                $warnings[] = "{$name}: шифрата 0047 значи неполно работно време, а часовите се како за полно.";
            }

            // Очекувањето се сведува по истото правило на MonthCoverage со
            // кое PayrollRunService::open() ги пресметал и вистинските часови,
            // па делумен месец (нов/заминат вработен) не е повеќе аномалија —
            // и двете страни на споредбата се сведени на истиот период на
            // покриеност. Само стварен недостиг под тоа сведено очекување
            // предупредува: работник со полно работно време на боледување,
            // на пример.
            $expectedHours = $employee->coverageIn($run->year, $run->month)->hours($fund);

            if ($employee->insurance_type_code === '0050' && $worked < $expectedHours) {
                $warnings[] = "{$name}: шифрата 0050 значи полно работно време, а часовите се помалку од очекуваните за покриениот период.";
            }

            // Директна противречност меѓу шифрата и договорот (weekly_hours),
            // не меѓу шифрата и внесените часови оваа пресметка: 0050 со
            // неделен фонд под 40 часа, или 0047 со точно 40. Ова е случајот
            // што двете претходни проверки го пропуштаат — кога договорениот
            // неделен фонд веќе е сведен да одговара на погрешната шифра, па
            // часовите излегуваат точно колку што „треба“ и ниту едно
            // отстапување не се појавува во пресметката. Пораката упатува кон
            // картонот на вработениот, не кон пресметката, зашто таму е
            // противречноста.
            if ($employee->insurance_type_code === '0050' && $employee->weekly_hours < 40) {
                $warnings[] = "{$name}: шифрата 0050 значи полно работно време, а во картонот на вработениот неделниот фонд е под 40 часа.";
            }

            if ($employee->insurance_type_code === '0047' && $employee->weekly_hours == 40) {
                $warnings[] = "{$name}: шифрата 0047 значи неполно работно време, а во картонот на вработениот неделниот фонд е 40 часа.";
            }
        }

        // Последна по ред, и само кога сè друго поминало: датотеката се гради
        // за да се провери, а градењето претпоставува дека податоците што
        // проверките погоре ги бараат се тука. Кога веќе има грешка, извозот и
        // онака е блокиран, па нема што да се добие од уште една.
        if ($errors === []) {
            $errors = self::levelSumErrors(MpinDocumentBuilder::build($run));
        }

        return new MpinValidationResult(array_values($errors), array_values($warnings));
    }

    /**
     * „Збировите на трите нивоа се совпаѓаат до денар" од спецификацијата.
     *
     * Намерно се гледа во ПРОИЗВЕДЕНАТА датотека, не во повторена пресметка на
     * истата аритметика: повторувањето на она што градителот го прави е
     * тавтологија што не може да падне, а проверка што не може да падне е
     * полоша од ниедна. Вака проверката е независна од начинот на кој
     * градителот стигнал до бројките и паѓа штом тој се врати на грешка —
     * што е точно нејзината работа, зашто расчекорот меѓу ниво 2 и ниво 3
     * веќе еднаш поминал незабележан.
     *
     * Јавна за да може да се провери и врз намерно расипана датотека; check()
     * ја повикува со она што градителот го дава.
     *
     * @return list<string>
     */
    public static function levelSumErrors(string $xml): array
    {
        $document = new SimpleXMLElement($xml);
        $errors = [];

        // Ниво 1 наспроти збирот на ниво 2, поле по поле.
        foreach (array_keys(MpinDocumentBuilder::AMOUNT_FIELDS) as $field) {
            $total = (int) $document->{$field.'Vk'};
            $sum = 0;

            foreach ($document->MpinCalculationSt as $employeeNode) {
                $sum += (int) $employeeNode->{$field.'VkVrab'};
            }

            if ($total !== $sum) {
                $errors[] = "Вкупниот износ {$field}Vk е {$total}, а збирот по работници е {$sum}.";
            }
        }

        // Ниво 2 наспроти збирот на ниво 3, работник по работник.
        foreach ($document->MpinCalculationSt as $employeeNode) {
            $gross = (int) $employeeNode->BrutoIznosVkVrab;
            $sum = 0;

            foreach ($employeeNode->MpinCalculationStDetail as $detail) {
                $sum += (int) $detail->BrutoIznos;
            }

            if ($gross !== $sum) {
                $ordinal = (string) $employeeNode->RedenBroj;
                $errors[] = "Работник со реден број {$ordinal}: бруто износот е {$gross}, а збирот на неговите ставки е {$sum}.";
            }
        }

        return $errors;
    }
}
