<?php

namespace App\Support\Payroll;

/**
 * Видот на обврзник од шифрарникот на УЈП, ограничен на двата што оваа
 * апликација навистина ги пресметува.
 *
 * Целиот шифрарник има 39 записи и сите се вчитани во `payroll_codes` за
 * евиденција, но паѓачкото мени нуди само овие два: секој друг вид носи свои
 * правила за пресметка што не се потврдени од ниту една вистинска датотека.
 */
enum MpinObvrznik: string
{
    case EMPLOYER = '110';
    case SELF_EMPLOYED = '111';

    public function label(): string
    {
        return match ($this) {
            self::EMPLOYER => 'Работодавач, правно лице',
            self::SELF_EMPLOYED => 'Самостоен вршител — интелектуална дејност',
        };
    }

    /**
     * Самостојниот вршител е ослободен од придонесот за вработување. Основа:
     * шифрата за ослободување 001 во шифрарникот на УЈП, „Самостоен вршител
     * ослободен од плаќање на придонес за вработување", потврдена со вистинска
     * поднесена датотека каде тој придонес е нула.
     */
    public function chargesUnemployment(): bool
    {
        return $this === self::EMPLOYER;
    }

    /**
     * Самостојниот вршител го плаќа личниот данок годишно преку годишна даночна
     * пријава, не месечно преку МПИН. Потврдено со вистинска поднесена датотека
     * каде и данокот и даночното намалување се нула, и потврдено од корисникот
     * како сметководител.
     */
    public function chargesMonthlyTax(): bool
    {
        return $this === self::EMPLOYER;
    }

    /**
     * Минат труд (0,5% за секоја завршена година стаж) е додаток на плата
     * што произлегува од работен однос по Законот за работни односи.
     * Самостојниот вршител нема работен однос со самиот себе — тој фактура,
     * не се вработува.
     *
     * Ова НЕ е потврдено со стаж во вистинската поднесена датотека: DatumPocetok
     * во МПИН ја носи само покриеноста на месецот (MonthCoverage — max од
     * почетокот на месецот и employed_on), не датумот на вработување, па
     * датотеката не открива колку долго лицето навистина работи. Основата е
     * друга: BrutoIznosVk во датотеката е точно `payroll_parameters.min_base`
     * за јануари 2026 (34571), законски утврдена основица за самостоен
     * вршител — и тоа во полн износ иако лицето работи 88 од 176 часа, не
     * преполовена. Законски фиксиран износ нема механизам да расте 0,5% по
     * година стаж; и шифрите на режимот во истата линија (SifraTipRabotenCas
     * 0047, SifraOsloboduvanje 001) го означуваат самостојниот режим, не
     * работен однос по ЗРО, на кој единствено минатиот труд се потпира.
     *
     * Чека потврда од сметководителот. Единственото end-to-end покривање е
     * `MpinDocumentBuilderTest::test_an_obvrznik_111_part_time_filing_is_reproduced_byte_for_byte`,
     * чиј `employed_on` е нарочно поставен подалеку наназад за да го „опфати"
     * овој гејт — самата датотека не докажува ништо за тоа поле.
     */
    public function paysSeniorityBonus(): bool
    {
        return $this === self::EMPLOYER;
    }
}
